"""Standalone HTML reports.

Self-contained by design: the stylesheet and script live in sitediff/templates
and are inlined at build time, so a report is one file with no network access
of any kind. That matters because reports get attached to CI runs and opened on
machines that have no route to anything.

Edit the look in templates/report.css and templates/report.js rather than here.
"""

from __future__ import annotations

import html
import math
from functools import lru_cache
from pathlib import Path

from .config import Profile
from .engine import DiffResult, Op, Status

TEMPLATE_DIR = Path(__file__).resolve().parent / "templates"
RING_RADIUS = 26


@lru_cache(maxsize=4)
def _asset(name: str) -> str:
    path = TEMPLATE_DIR / name
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def _esc(text: str) -> str:
    return html.escape(str(text), quote=True)


def _tile(label: str, value: str, kind: str = "") -> str:
    return (f'<div class="tile {kind}"><div class="k">{_esc(label)}</div>'
            f'<div class="v">{_esc(value)}</div></div>')


# A real minus sign reads better than a hyphen at tile size. It is written as a
# literal here and as an entity in markup, since _esc would escape the entity.
MINUS = "\u2212"


def _ring_tile(label: str, ratio: float) -> str:
    circ = 2 * math.pi * RING_RADIUS
    offset = circ * (1 - max(0.0, min(1.0, ratio)))
    return (
        f'<div class="tile"><div class="k">{_esc(label)}</div>'
        f'<div class="ring" style="--circ:{circ:.1f};--offset:{offset:.1f}">'
        f'<svg width="64" height="64" viewBox="0 0 64 64" aria-hidden="true">'
        f'<circle class="track" cx="32" cy="32" r="{RING_RADIUS}"/>'
        f'<circle class="value" cx="32" cy="32" r="{RING_RADIUS}"/></svg>'
        f'<div class="v">{ratio:.0%}</div></div></div>'
    )


def _shell(title: str, badge: str, subtitle: str, body: str) -> str:
    clean = badge == "CLEAN"
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{_esc(title)}</title>
<style>{_asset("report.css")}</style></head>
<body><div class="wrap">
<div class="top">
  <div>
    <h1 class="title">{_esc(title)}</h1>
    <p class="subtitle">{_esc(subtitle)}</p>
  </div>
  <div class="spacer"></div>
  <span class="badge {'clean' if clean else 'drift'}"><span class="dot"></span>{badge}</span>
  <button class="icon-btn" id="theme-toggle" type="button">Theme</button>
</div>
{body}
<footer>
  Generated by sitediff. Values shown have passed the profile's redaction rules.
  Press <kbd>/</kbd> to search, <kbd>Esc</kbd> to clear.
</footer>
</div>
<script>{_asset("report.js")}</script>
</body></html>
"""


def _toolbar(kinds: list[tuple[str, str]], findings: int) -> str:
    chips = "".join(
        f'<button class="chip" type="button" data-filter="{k}" '
        f'aria-pressed="{"true" if k == "all" else "false"}">{_esc(label)}</button>'
        for k, label in kinds
    )
    return (
        f'<div class="toolbar">{chips}'
        f'<input class="search" id="search" type="search" '
        f'placeholder="Filter by text…" aria-label="Filter findings">'
        f'<button class="icon-btn" id="expand-all" type="button">Collapse all</button>'
        f'<span class="count" id="visible-count">{findings} findings</span></div>'
    )


def _meta(result: DiffResult) -> str:
    rows = [("left", result.left.path), ("right", result.right.path),
            ("mode", result.mode.value)]
    if result.ignored:
        rows.append(("ignored by profile", str(result.ignored)))
    if result.noise_suppressed:
        rows.append(("suppressed as noise", str(result.noise_suppressed)))
    if result.accepted:
        rows.append(("suppressed as accepted", str(result.accepted)))
    items = "".join(f"<dt>{_esc(k)}</dt><dd>{_esc(v)}</dd>" for k, v in rows)
    for change in result.meta_changes:
        items += (f'<dt>{_esc(change.key)}</dt><dd class="changed">'
                  f'{_esc(change.left or "absent")} → {_esc(change.right or "absent")}</dd>')
    return f'<div class="meta"><dl>{items}</dl></div>'


def _fields(result: DiffResult) -> str:
    symbols = {Op.ADD: ("+", "add"), Op.REMOVE: ("&minus;", "remove"), Op.ALTER: ("~", "alter")}
    rows = []
    for change in result.field_changes:
        symbol, css = symbols[change.op]
        left = _esc(change.left) if change.left else '<span class="n">absent</span>'
        right = _esc(change.right) if change.right else '<span class="n">absent</span>'
        rows.append(
            f'<tr class="{css}" data-op="{css}"><td class="s">{symbol}</td>'
            f'<td class="f mono">{_esc(change.path)}</td>'
            f'<td class="v mono">{left}</td><td class="v mono">{right}</td></tr>'
        )
    if not rows:
        return ('<div class="empty-state"><div class="big">✓</div>'
                "No field differences.</div>")
    return ('<div class="panel"><div class="rows"><table><thead><tr>'
            "<th></th><th>field</th><th>left</th><th>right</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table></div></div>")


def _hunks(result: DiffResult) -> str:
    css = {Op.ADD: "add", Op.REMOVE: "remove", Op.EQUAL: "equal"}
    marks = {Op.ADD: "+", Op.REMOVE: "&minus;", Op.EQUAL: ""}
    blocks = []
    for hunk in result.hunks:
        rows = []
        adds = sum(1 for ln in hunk.lines if ln.op is Op.ADD)
        dels = sum(1 for ln in hunk.lines if ln.op is Op.REMOVE)
        for line in hunk.lines:
            kind = css[line.op]
            rows.append(
                f'<tr class="{"context" if kind == "equal" else kind}" data-op="{kind}">'
                f'<td class="n">{line.left_no or ""}</td>'
                f'<td class="n">{line.right_no or ""}</td>'
                f'<td class="s">{marks[line.op]}</td>'
                f'<td class="t mono">{_esc(line.text)}</td></tr>'
            )
        blocks.append(
            f'<details class="hunk" open><summary><span class="chev">&rsaquo;</span>'
            f'<span class="mono">{_esc(hunk.header)}</span>'
            f'<span class="tally">+{adds} &minus;{dels}</span></summary>'
            f'<div class="rows"><table><tbody>{"".join(rows)}</tbody></table></div>'
            f"</details>"
        )
    if not blocks:
        return ('<div class="empty-state"><div class="big">✓</div>'
                "No differences in visible content.</div>")
    return "".join(blocks)


def build_html_report(result: DiffResult, profile: Profile) -> str:
    clean = result.status is Status.CLEAN
    tiles = [
        _tile("added", f"+{result.added}", "add"),
        _tile("removed", f"\u2212{result.removed}", "del"),
    ]
    if result.structured:
        tiles.append(_tile("altered", f"~{result.altered}", "alt"))
    tiles.append(_ring_tile("similarity", result.similarity))

    kinds = [("all", "All"), ("add", "Added"), ("remove", "Removed")]
    if result.structured:
        kinds.append(("alter", "Altered"))

    body = (
        f'<div class="tiles">{"".join(tiles)}</div>'
        f"{_meta(result)}"
        f"{_toolbar(kinds, result.changed)}"
        f"{_fields(result) if result.structured else _hunks(result)}"
    )
    subtitle = f"profile: {profile.name} · {Path(result.left.path).name} vs " \
               f"{Path(result.right.path).name}"
    return _shell("sitediff", "CLEAN" if clean else "DRIFT", subtitle, body)


def build_run_report(report, profile: Profile) -> str:
    clean = not (report.drift or report.failed)
    tiles = [
        _tile("entities", str(len(report.results))),
        _tile("clean", str(report.clean), "add"),
        _tile("drift", str(report.drift), "alt"),
        _tile("failed", str(report.failed), "del"),
    ]
    total = len(report.results) or 1
    tiles.append(_ring_tile("passing", report.clean / total))

    rows = []
    for item in report.drifted:
        counts = ("" if item.status == "error"
                  else f"+{item.added} \u2212{item.removed} ~{item.altered}")
        rows.append(
            f'<tr data-op="{_esc(item.status)}">'
            f'<td class="f mono">{_esc(item.key)}</td>'
            f'<td><span class="status-pill {_esc(item.status)}">{_esc(item.status)}</span></td>'
            f'<td class="mono">{_esc(counts)}</td>'
            f'<td class="t">{_esc(item.detail[:600])}</td></tr>'
        )
    if rows:
        table = ('<div class="panel"><div class="rows">'
                 '<table data-sortable><thead><tr>'
                 '<th>entity <span class="dir"></span></th>'
                 '<th>status <span class="dir"></span></th>'
                 '<th>changes <span class="dir"></span></th>'
                 '<th>detail <span class="dir"></span></th>'
                 f"</tr></thead><tbody>{''.join(rows)}</tbody></table></div></div>")
    else:
        table = ('<div class="empty-state"><div class="big">✓</div>'
                 "Every entity matched.</div>")

    extras = []
    if report.accepted:
        extras.append(f"{report.accepted} finding(s) suppressed as accepted")
    if report.discovery_failures:
        extras.append(f"{len(report.discovery_failures)} discovery page(s) failed")
    if report.run_id is not None:
        extras.append(f"run #{report.run_id} in {report.db_path}")
    meta = ""
    if extras:
        items = "".join(f"<dt>note</dt><dd>{_esc(e)}</dd>" for e in extras)
        meta = f'<div class="meta"><dl>{items}</dl></div>'

    run_toolbar = _toolbar(
        [("all", "All"), ("drift", "Drift"), ("error", "Failed")], len(report.drifted)
    )
    body = (
        f'<div class="tiles">{"".join(tiles)}</div>{meta}'
        f"{run_toolbar}"
        f"{table}"
    )
    subtitle = f"profile: {profile.name} · {len(report.results)} entities in " \
               f"{report.seconds:.1f}s"
    return _shell("sitediff run", "CLEAN" if clean else "DRIFT", subtitle, body)


def _write(content: str, out_path: str) -> str:
    path = Path(out_path)
    if path.parent and not path.parent.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return str(path)


def write_html_report(result: DiffResult, out_path: str, profile: Profile) -> str:
    return _write(build_html_report(result, profile), out_path)


def write_run_report(report, out_path: str, profile: Profile) -> str:
    return _write(build_run_report(report, profile), out_path)
